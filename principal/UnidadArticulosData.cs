                    command.Parameters.AddWithValue(":prmeliminar", NpgsqlTypes.NpgsqlDbType.Boolean, prmeliminar);
                   
                    command.CommandType = CommandType.StoredProcedure;
                    command.ExecuteNonQuery();

                 
                    dataAdapter.Dispose();

                    t.Commit();
                    t.Dispose();
                    conn.Close();
                }
                catch (Exception ex)
                {
                    t.Dispose();
                    conn.Close();
                    throw new Exception(ex.Message);
